"""Tests that the tested examples under docs/examples/ stay valid.

docs/examples/run-record.json must keep the same structure (keys and value
types) as a run record generated by generate_run_report.py, so the low-level
design can link to it instead of pasting a copy that can drift from the code.
"""

import importlib.util
import json
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
EXAMPLES_DIR = REPO_ROOT / "docs" / "examples"
REPORT_PATH = (
    REPO_ROOT
    / "packages"
    / "shared-workflows"
    / "actions"
    / "publish-run-report"
    / "generate_run_report.py"
)
REPORT_SPEC = importlib.util.spec_from_file_location("generate_run_report", REPORT_PATH)
if REPORT_SPEC is None or REPORT_SPEC.loader is None:
    raise ImportError(f"Unable to load run report generator from {REPORT_PATH}")
REPORT = importlib.util.module_from_spec(REPORT_SPEC)
REPORT_SPEC.loader.exec_module(REPORT)

# environments[].error is only present when a deployment result file was
# missing; a clean, all-passed run (the example) never has it.
OPTIONAL_KEYS = {"error"}


def generated_clean_run_record() -> dict:
    """Build a run record for an all-passed push to main, the same shape the example shows."""
    environment = {
        "run_id": "555",
        "repository": "UKHSA-Internal/sample-service",
        "commit_sha": "0123456789abcdef0123456789abcdef01234567",
        "ref": "refs/heads/main",
        "workflow_ref": "UKHSA-Internal/sample-service/.github/workflows/pipeline.yml@refs/heads/main",
        "workflow_sha": "abcdef0123456789abcdef0123456789abcdef01",
        "trigger_type": "push",
        "start_time": "2026-11-12T09:00:00Z",
        "check_result": "success",
        "test_result": "success",
        "scan_result": "success",
        "build_result": "success",
        "deploy_dev_result": "success",
        "deploy_preprod_result": "success",
        "deploy_prod_result": "success",
    }
    image_tag = "sample-service:0123456789abcdef0123456789abcdef01234567"

    def deployment(name, category, verified_at):
        return {
            "name": name,
            "category": category,
            "deploy_outcome": "success",
            "verify_outcome": "success",
            "image_tag": image_tag,
            "verified_at": verified_at,
        }

    deployment_results = [
        deployment("dev-env-1", "Development", "2026-11-12T09:04:00Z"),
        deployment("preprod-env-1", "Pre-production", "2026-11-12T09:08:00Z"),
        deployment("prod-env-1", "Production", "2026-11-12T09:12:00Z"),
    ]
    return REPORT.create_report(environment, "2026-11-12T09:13:00Z", deployment_results)


def assert_same_structure(actual, expected, path="$"):
    """Assert actual and expected have the same keys and value types at every level.

    Keys in OPTIONAL_KEYS may be present on one side and absent on the other;
    when present on both, their values are still compared structurally.
    """
    if isinstance(expected, dict):
        if not isinstance(actual, dict):
            raise AssertionError(f"{path}: expected a mapping, got {type(actual).__name__}")
        expected_keys = set(expected)
        actual_keys = set(actual)
        missing = (expected_keys - OPTIONAL_KEYS) - actual_keys
        extra = (actual_keys - OPTIONAL_KEYS) - expected_keys
        if missing:
            raise AssertionError(f"{path}: missing keys {sorted(missing)}")
        if extra:
            raise AssertionError(f"{path}: unexpected keys {sorted(extra)}")
        for key in expected_keys & actual_keys:
            assert_same_structure(actual[key], expected[key], f"{path}.{key}")
        return

    if isinstance(expected, list):
        if not isinstance(actual, list):
            raise AssertionError(f"{path}: expected a list, got {type(actual).__name__}")
        for index, (actual_item, expected_item) in enumerate(zip(actual, expected)):
            assert_same_structure(actual_item, expected_item, f"{path}[{index}]")
        return

    if expected is None or actual is None:
        return  # Several fields (governance.*, verified_at on failure) are nullable.

    if type(actual) is not type(expected):
        raise AssertionError(
            f"{path}: type mismatch, expected {type(expected).__name__}, got {type(actual).__name__}"
        )


class DocsExamplesTests(unittest.TestCase):
    def test_run_record_example_matches_generated_structure(self):
        example = json.loads((EXAMPLES_DIR / "run-record.json").read_text(encoding="utf-8"))
        generated = generated_clean_run_record()
        assert_same_structure(example, generated)
        assert_same_structure(generated, example)

    def test_pipeline_settings_example_is_valid_yaml(self):
        import yaml

        settings = yaml.safe_load((EXAMPLES_DIR / "pipeline-settings.yml").read_text(encoding="utf-8"))
        self.assertIsInstance(settings, dict)
        self.assertIn("environments", settings)


if __name__ == "__main__":
    unittest.main()
